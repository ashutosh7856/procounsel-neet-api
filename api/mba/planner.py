@router.post("/me/plan/generate", response_model=WeekPlan)
def generate_plan(week: str | None = Query(default=None), user: CurrentUser = Depends(student),
                  db: SafeFirestore = Depends(get_db)) -> dict[str, Any]:
    today = local_date(utcnow())
    week_start = _week_param(week, today)
    if week_start + timedelta(days=6) < today:
        raise HTTPException(409, "That week is over; plans can only be built for this week or later.")
    if (week_start - today).days > 366:
        raise HTTPException(422, "week must be within a year of today.")
    if load_profile(db, user.user_id) is None:
        raise HTTPException(409, "Complete onboarding first; the plan is built from your profile.")
    generate_week(db, user, week_start)
    return build_week_response(db, user, week_start)


