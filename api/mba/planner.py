def _week_param(week: str | None, today: date) -> date:
    if week is None:
        return week_start_of(today)
    day = parse_day(week)
    if day is None:
        raise HTTPException(422, "week must be a date (YYYY-MM-DD).")
    return week_start_of(day)


def _check_task_date(day: date, today: date) -> None:
    if abs((day - today).days) > 366:
        raise HTTPException(422, "date must be within a year of today.")


def build_week_response(db: SafeFirestore, user: CurrentUser, week_start: date) -> dict[str, Any]:
    bank = get_bank(db)
    now = utcnow()
    today = local_date(now)
    stats = user_stats(db, user.user_id)
    attempts = user_attempts(db, bank, user)
    tasks = _week_tasks(db, user.user_id, week_start)
    applied = auto_complete(db, bank, stats, attempts, tasks, week_start, today)
    rows = [task_payload(doc_id, {**data, **applied.get(doc_id, {})}) for doc_id, data, _ in tasks]
    kept = [{**data, "id": doc_id} for doc_id, data, _ in tasks if not _replaceable(data, today)]
    profile = load_profile(db, user.user_id)
    _specs, basis = build_week_plan(plan_inputs(profile, stats, bank, attempts, week_start, today, now, kept))

    study = set(basis["studyDays"])
    exam = parse_day(basis["examDate"])
    days = []
    for i in range(7):
        day = week_start + timedelta(days=i)
        day_tasks = sorted((r for r in rows if r["date"] == day.isoformat()), key=lambda r: (r["order"], r["createdAt"], r["id"]))
        days.append({
            "date": day.isoformat(),
            "weekday": js_weekday(day),
            "rest": js_weekday(day) not in study,
            "examDay": exam == day,
            "plannedMinutes": sum(r["minutes"] for r in day_tasks if r["status"] != "skipped"),
            "tasks": day_tasks,
        })
    in_week = [r for d in days for r in d["tasks"]]
    return {
        "weekStart": week_start.isoformat(),
        "weekEnd": (week_start + timedelta(days=6)).isoformat(),
        "today": today.isoformat(),
        "generated": any(r["source"] == "generated" for r in rows),
        "canGenerate": week_start + timedelta(days=6) >= today,
        "days": days,
        "summary": {
            "planned": len(in_week),
            "done": sum(1 for r in in_week if r["status"] == "done"),
            "skipped": sum(1 for r in in_week if r["status"] == "skipped"),
            "pending": sum(1 for r in in_week if r["status"] == "pending"),
            "plannedMinutes": sum(r["minutes"] for r in in_week if r["status"] != "skipped"),
            "doneMinutes": sum(r["minutes"] for r in in_week if r["status"] == "done"),
        },
        "basis": basis,
    }


