"""Weekly study planner: ``mbaStudyTasks`` (one document per task).

The plan is generated by a deterministic, rule-based generator (no AI): the same
inputs always give the same week. Every rule is reported back to the student in
``basis.rules`` so the plan is transparent. Rules (``planner-v1``):

* Time: ``weeklyStudyHours`` is split evenly over the profile's study days; other
  days are rest days. Nothing is planned on or after the exam date, and the day
  before the exam only gets light revision.
* Mocks per week by weeks left to the exam: > 8 weeks → 1, 5–8 → 2, final 4 → 3
  (1 when no exam date is known). A student who has not submitted a mock yet gets a
  full mock first (diagnostic); beginners more than 8 weeks out take a sectional of
  their weakest section instead. Mocks never take more than 60% of the week's time
  (a full mock is downgraded to a sectional, then dropped). Mocks go on the latest
  study days, spaced out.
* Practice time per section is weighted: a section with ≥ 5 questions answered gets
  weight ``1 + 2 × max(0, 0.75 − accuracy)``; others weight 1. Blocks are handed out
  in proportion to the weights. The weakest topic of a section (≥ 3 answered,
  accuracy < 60%) is named in the task.
* Due mistakes → a revision task on every third study day.
* Daily challenge (10 min) on every study day with ≥ 30 minutes.
* Learn sessions (30 min, weakest section): beginner 2 / intermediate 1 / advanced 0
  per week, none in the final 4 weeks.

Generating a week is idempotent. Only pending, unedited, generated tasks dated today
or later are replaced; done, skipped, edited and custom tasks are never touched, and
they count against that day's time (and the week's mock count).

Tasks are queried by ``userWeek`` (``{userId}|{weekStart}``), a single-field equality,
so no composite index is needed.
"""

