@router.patch("/me/plan/tasks/{task_id}", response_model=PlanTask)
def patch_task(task_id: str, body: TaskPatch, user: CurrentUser = Depends(student),
               db: SafeFirestore = Depends(get_db)) -> dict[str, Any]:
    _owned(db, task_id, user)
    sent = body.model_dump(exclude_unset=True)
    if not sent or any(v is None for v in sent.values()):
        raise HTTPException(422, "Send at least one of status, date, title, minutes (not null).")
    now = utcnow()
    today = local_date(now)
    stamp = iso(now)
    if "date" in sent:
        _check_task_date(date.fromisoformat(sent["date"]), today)

    def mutate(current: dict[str, Any] | None) -> tuple[dict[str, Any] | None, dict[str, Any]]:
        if current is None or current.get("userId") != user.user_id:
            raise HTTPException(404, "Task not found.")
        fields: dict[str, Any] = {}
        if "status" in sent and sent["status"] != current.get("status"):
            fields["status"] = sent["status"]
            fields["completedAt"] = stamp if sent["status"] == "done" else None
            fields["autoCompleted"] = False
            if sent["status"] != "done":
                fields["completedByAttempt"] = None
        if "date" in sent and sent["date"] != current.get("date"):
            new_week = week_start_of(date.fromisoformat(sent["date"]))
            fields.update({"date": sent["date"], "weekStart": new_week.isoformat(), "userWeek": user_week(user.user_id, new_week), "edited": True})
        for key in ("title", "minutes"):
            if key in sent and sent[key] != current.get(key):
                fields[key] = sent[key]
                fields["edited"] = True
        if not fields:
            return None, current
        fields["updatedAt"] = stamp
        return fields, {**current, **fields}

    return task_payload(task_id, occ_update(db, TASKS, task_id, mutate))


@router.post("/me/plan/tasks", response_model=PlanTask, status_code=201)
def create_task(body: TaskCreate, user: CurrentUser = Depends(student), db: SafeFirestore = Depends(get_db)) -> dict[str, Any]:
    now = utcnow()
    day = date.fromisoformat(body.date)
    _check_task_date(day, local_date(now))
    week_start = week_start_of(day)
    if sum(1 for _, t, _ in _week_tasks(db, user.user_id, week_start) if t.get("source") == "custom") >= MAX_CUSTOM_PER_WEEK:
        raise HTTPException(409, f"A week can hold at most {MAX_CUSTOM_PER_WEEK} tasks of your own.")
    task_id = f"{user.user_id}_c_{uuid.uuid4().hex[:16]}"
    stamp = iso(now)
    doc = {
        "userId": user.user_id, "userWeek": user_week(user.user_id, week_start), "weekStart": week_start.isoformat(),
        "date": body.date, "type": body.type, "title": body.title.strip(), "detail": (body.detail or "").strip() or None,
        "section": body.section, "topic": None, "questionCount": None, "minutes": body.minutes, "href": body.href,
        "status": "pending", "source": "custom", "generatedBy": None, "edited": False, "autoCompleted": False,
        "completedAt": None, "order": 900, "createdAt": stamp, "updatedAt": stamp,
    }

    def mutate(current: dict[str, Any] | None) -> tuple[dict[str, Any] | None, dict[str, Any]]:
        if current is not None:
            raise HTTPException(409, "Please retry.")
        return doc, doc

    return task_payload(task_id, occ_update(db, TASKS, task_id, mutate))


@router.delete("/me/plan/tasks/{task_id}", response_model=DeleteResponse)
def delete_task(task_id: str, user: CurrentUser = Depends(student), db: SafeFirestore = Depends(get_db)) -> dict[str, Any]:
    """Only the student's own (custom) tasks can be deleted; generated ones are skipped instead."""
    _owned(db, task_id, user)
    ref = db.collection(TASKS).document(task_id)
    snap = ref.get(timeout=DB_TIMEOUT)
    data = as_dict(snap)
    if data is None or data.get("userId") != user.user_id:
        raise HTTPException(404, "Task not found.")
    if data.get("source") != "custom":
        raise HTTPException(409, "Planned tasks can be skipped or moved, not deleted.")
    ref.delete(option=_FirestoreClient.write_option(last_update_time=snap.update_time), timeout=DB_TIMEOUT)
    return {"deleted": True}
