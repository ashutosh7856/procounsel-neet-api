_DATE = r"^\d{4}-\d{2}-\d{2}$"


def _valid_day(value: str | None) -> str | None:
    if value is not None:
        date.fromisoformat(value)
    return value


def _app_href(value: str | None) -> str | None:
    if value is not None and not (value.startswith("/mba/") and not value.startswith("//")):
        raise ValueError("href must be an in-app path starting with /mba/")
    return value


