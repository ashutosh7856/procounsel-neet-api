# ---------------------------------------------------------------- dates
def week_start_of(day: date) -> date:
    """Weeks run Monday to Sunday."""
    return day - timedelta(days=day.weekday())


def js_weekday(day: date) -> int:
    """0 = Sunday … 6 = Saturday (the profile's ``studyDays`` numbering)."""
    return (day.weekday() + 1) % 7


def parse_day(value: Any) -> date | None:
    if not isinstance(value, str):
        return None
    try:
        return date.fromisoformat(value)
    except ValueError:
        return None


def user_week(user_id: str, week_start: date) -> str:
    return f"{user_id}|{week_start.isoformat()}"


@lru_cache(maxsize=1)
def official_cat_date() -> date | None:
    """The CAT exam date from data/mba/exams/cat.json (``keyDates`` entry for the exam)."""
    try:
        data = json.loads((ROOT / "data" / "mba" / "exams" / "cat.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    for entry in data.get("keyDates") or []:
        if not isinstance(entry, dict):
            continue
        event = str(entry.get("event") or "").lower()
        if "exam" in event and "registration" not in event and "admit" not in event:
            found = parse_day(entry.get("date"))
            if found:
                return found
    return None


def exam_date_for(profile: dict[str, Any] | None) -> tuple[date | None, str | None]:
    """The student's own CAT date if set, else the official one."""
    own = parse_day((profile or {}).get("examDate"))
    if own:
        return own, "profile"
    official = official_cat_date()
    return (official, "official") if official else (None, None)


def _round5(value: float) -> int:
    return int(5 * math.floor(value / 5 + 1e-9))


def _plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


# ---------------------------------------------------------------- generator (pure)
@dataclass
class SectionInput:
    attempted: int = 0
    accuracy: float | None = None
    weak_topic: str | None = None
    weak_topic_accuracy: float | None = None
    weak_topic_attempted: int = 0


@dataclass
class PlanInputs:
    week_start: date
    today: date
    exam_date: date | None
    exam_date_source: str | None
    weekly_hours: float
    study_days: list[int]
    level: str
    sections: dict[str, SectionInput]
    mistakes_due: int
    mocks_submitted: int
    daily_available: bool = True
    kept: list[dict[str, Any]] = field(default_factory=list)  # tasks the generator must not replace


def mocks_per_week(weeks_left: int | None) -> int:
    if weeks_left is None or weeks_left > 8:
        return 1
    if weeks_left > 4:
        return 2
    return 3


def section_weight(section: SectionInput) -> float:
    if section.attempted < WEAK_MIN_ATTEMPTED or section.accuracy is None:
        return 1.0
    return round(1 + 2 * max(0.0, 0.75 - section.accuracy), 2)


def _pct(value: float | None) -> str:
    return f"{round((value or 0) * 100)}%"


def build_week_plan(inp: PlanInputs) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Return (task specs, basis). Pure: no I/O, no clock."""
    days = [inp.week_start + timedelta(days=i) for i in range(7)]
    study_set = {d for d in inp.study_days if isinstance(d, int) and 0 <= d <= 6} or {1, 2, 3, 4, 5, 6}
    exam = inp.exam_date
    rules: list[str] = []

    per_day = _round5(inp.weekly_hours * 60 / len(study_set))
    rules.append(
        f"{inp.weekly_hours:g} h a week over {_plural(len(study_set), 'study day')} → about {per_day} min per study day. "
        f"Rest days: {', '.join(WEEKDAY[d] for d in range(7) if d not in study_set) or 'none'}."
    )

    weeks_left: int | None = None
    if exam:
        days_left = (exam - inp.week_start).days
        weeks_left = max(0, math.ceil(days_left / 7))
    target_mocks = mocks_per_week(weeks_left)
    if exam:
        whose = "your profile" if inp.exam_date_source == "profile" else "the official CAT date"
        band = "more than 8 weeks out" if (weeks_left or 0) > 8 else ("5–8 weeks out" if (weeks_left or 0) > 4 else "final 4 weeks")
        rules.append(f"CAT on {exam.isoformat()} ({whose}): {_plural(weeks_left or 0, 'week')} left, {band} → {_plural(target_mocks, 'mock')} this week.")
    else:
        rules.append("No CAT date yet → 1 mock a week. Add your exam date in Profile to pace the plan.")

    eve = exam - timedelta(days=1) if exam else None
    eligible = [d for d in days if js_weekday(d) in study_set and d >= inp.today and (exam is None or d < exam)]
    if exam and exam in days:
        rules.append("Nothing is planned on exam day or after it; the day before gets light revision only.")

    # Kept tasks (done / skipped / edited / custom): they use their day's time and count as mocks.
    kept_minutes: dict[date, int] = {}
    kept_types: dict[date, set[str]] = {}
    kept_mocks = 0
    for task in inp.kept:
        day = parse_day(task.get("date"))
        if task.get("type") in MOCK_TYPES:
            kept_mocks += 1
        if day is None:
            continue
        if task.get("status") != "skipped":
            kept_minutes[day] = kept_minutes.get(day, 0) + int(task.get("minutes") or 0)
        kept_types.setdefault(day, set()).add(str(task.get("type")))

    # Section weights and the weakest section.
    weights = {sid: section_weight(inp.sections.get(sid, SectionInput())) for sid in SECTION_IDS}
    weakest = max(SECTION_IDS, key=lambda s: (weights[s], -SECTION_IDS.index(s)))
    for sid in SECTION_IDS:
        sec = inp.sections.get(sid, SectionInput())
        if weights[sid] > 1:
            rules.append(f"{sid} gets more practice time: accuracy {_pct(sec.accuracy)} over {sec.attempted} questions (weight {weights[sid]:g}).")
    if all(w == 1 for w in weights.values()):
        rules.append(f"Practice is split evenly across VARC, DILR and QA until a section has {WEAK_MIN_ATTEMPTED}+ answered questions below 75% accuracy.")

    # Mocks: count, kind, placement.
    mock_days_pool = [d for d in eligible if d != eve]
    # Never mocks on back-to-back study days: at most every other remaining study day.
    n_mocks = max(0, min(target_mocks - kept_mocks, math.ceil(len(mock_days_pool) / 2)))
    if 0 < n_mocks < target_mocks - kept_mocks:
        rules.append(f"Only {_plural(len(mock_days_pool), 'study day')} left this week → {_plural(n_mocks, 'mock')}, never on back-to-back days.")
    if kept_mocks and target_mocks:
        rules.append(f"{_plural(kept_mocks, 'mock')} already on this week's plan count towards the {target_mocks}.")
    full = inp.mocks_submitted == 0 or inp.level != "beginner" or (weeks_left is not None and weeks_left <= 8)
    kinds = ["full_mock" if full else "sectional_mock"] * n_mocks
    if inp.mocks_submitted == 0 and n_mocks:
        kinds[0] = "full_mock"
        rules.append("No mock submitted yet → the first one is a full mock, as a diagnostic.")
    elif not full and n_mocks:
        rules.append(f"Beginner and more than 8 weeks out → sectional mocks in your weakest section ({weakest}).")

    budget = {d: max(0, per_day - kept_minutes.get(d, 0)) for d in eligible}
    total_budget = sum(budget.values())

    def mock_minutes(kind: str) -> int:
        return FULL_MOCK_MINUTES if kind == "full_mock" else SECTIONAL_MOCK_MINUTES

    capped = False
    while kinds and sum(map(mock_minutes, kinds)) > MAX_MOCK_SHARE * total_budget:
        capped = True
        if "full_mock" in kinds:
            kinds[len(kinds) - 1 - kinds[::-1].index("full_mock")] = "sectional_mock"
        else:
            kinds.pop()
    if capped:
        rules.append(f"Mocks are capped at {int(MAX_MOCK_SHARE * 100)}% of the week's remaining time, so this week has fewer or shorter mocks.")

    mock_on: dict[date, str] = {}
    n = len(mock_days_pool)
    for i, kind in enumerate(kinds):
        mock_on[mock_days_pool[n - 1 - (i * n) // len(kinds)]] = kind

    # A mock day uses at least the mock's time; the excess comes out of the other days.
    excess = sum(max(0, mock_minutes(k) - budget[d]) for d, k in mock_on.items())
    others = [d for d in eligible if d not in mock_on and d != eve]
    if excess and others:
        cut = excess / len(others)
        for d in others:
            budget[d] = max(0, _round5(budget[d] - cut))

    if inp.mistakes_due:
        rules.append(f"{_plural(inp.mistakes_due, 'mistake')} due for review → a revision task every third study day.")
    learn_target = 0 if (weeks_left is not None and weeks_left <= 4) else {"beginner": 2, "intermediate": 1}.get(inp.level, 0)
    if learn_target:
        rules.append(f"{inp.level.capitalize()} level → {_plural(learn_target, 'learn session')} a week ({weakest}).")
    rules.append("Tasks are never planned before today. Done, skipped, edited and your own tasks are never changed.")

    specs: list[dict[str, Any]] = []
    order = 0

    def add(day: date, kind: str, title: str, detail: str, minutes: int, href: str,
            section: str | None = None, topic: str | None = None, questions: int | None = None) -> None:
        nonlocal order
        order += 1
        same = sum(1 for s in specs if s["date"] == day.isoformat() and s["type"] == kind and s["section"] == section)
        key = f"{day.isoformat()}-{kind}" + (f"-{section}" if section else "") + (f"-{same + 1}" if same else "")
        specs.append({"key": key, "date": day.isoformat(), "type": kind, "title": title, "detail": detail, "minutes": minutes,
                      "href": href, "section": section, "topic": topic, "questionCount": questions, "order": order})

    assigned = {sid: 0 for sid in SECTION_IDS}

    def next_section() -> str:
        pick = max(SECTION_IDS, key=lambda s: (weights[s] / (assigned[s] + 1), -SECTION_IDS.index(s)))
        assigned[pick] += 1
        return pick

    def practice(day: date, minutes: int) -> None:
        sid = next_section()
        sec = inp.sections.get(sid, SectionInput())
        questions = max(5, round(minutes / MINUTES_PER_QUESTION))
        topic = sec.weak_topic
        detail = f"{questions} questions, about {minutes} min."
        if topic:
            detail += f" Focus on {topic}: {_pct(sec.weak_topic_accuracy)} over {sec.weak_topic_attempted} questions so far."
        add(day, "practice", f"Practise {sid}" + (f" · {topic}" if topic else ""), detail, minutes,
            f"/mba/practice?section={sid}", section=sid, topic=topic, questions=questions)

    learn_left = learn_target
    for index, day in enumerate(eligible):
        taken = kept_types.get(day, set())
        left = budget[day]
        if day == eve:
            add(day, "revise_mistakes", "Light revision before CAT",
                "Skim your mistakes notebook and rest well. No new topics today.", min(30, max(15, left or 30)), "/mba/mistakes")
            continue
        if day in mock_on:
            kind = mock_on[day]
            if kind == "full_mock":
                add(day, kind, "Full CAT mock", "120 minutes under exam conditions, then 30 minutes reviewing every wrong answer.",
                    FULL_MOCK_MINUTES, "/mba/mocks")
            else:
                add(day, kind, f"{weakest} sectional mock", "40 minutes timed, then 15 minutes on the solutions.",
                    SECTIONAL_MOCK_MINUTES, "/mba/mocks", section=weakest)
            left -= mock_minutes(kind)
        if inp.daily_available and left >= 30 and "daily_challenge" not in taken:
            add(day, "daily_challenge", "Daily challenge", "Today's 5–10 questions.", DAILY_MINUTES, "/mba/daily")
            left -= DAILY_MINUTES
        if day in mock_on:
            pass  # a mock day keeps its leftover time for practice only
        elif inp.mistakes_due and index % 3 == 0 and left >= 15 and "revise_mistakes" not in taken:
            minutes = min(30, max(15, _round5(inp.mistakes_due * MINUTES_PER_QUESTION)))
            count = min(inp.mistakes_due, minutes // MINUTES_PER_QUESTION)
            add(day, "revise_mistakes", "Revise due mistakes", f"Retry {_plural(count, 'question')} you got wrong before.",
                minutes, "/mba/mistakes?due=true", questions=count)
            left -= minutes
        if learn_left and day not in mock_on and left >= LEARN_MINUTES + 15 and "learn" not in taken:
            add(day, "learn", f"Learn {weakest} concepts", f"A {SECTION_NAMES[weakest]} lesson before practising it.", LEARN_MINUTES,
                "/mba/learn", section=weakest)
            learn_left -= 1
            left -= LEARN_MINUTES
        if left >= 70:
            first = _round5(left / 2)
            practice(day, first)
            practice(day, _round5(left - first))
        elif left >= 15:
            practice(day, _round5(left))

    basis = {
        "ruleVersion": RULE_VERSION,
        "examDate": exam.isoformat() if exam else None,
        "examDateSource": inp.exam_date_source if exam else None,
        "weeksToExam": weeks_left,
        "weeklyStudyHours": inp.weekly_hours,
        "studyDays": sorted(study_set),
        "minutesPerStudyDay": per_day,
        "level": inp.level,
        "mocksThisWeek": target_mocks,
        "mistakesDue": inp.mistakes_due,
        "sections": [
            {"id": sid, "attempted": inp.sections.get(sid, SectionInput()).attempted,
             "accuracy": inp.sections.get(sid, SectionInput()).accuracy, "weight": weights[sid]}
            for sid in SECTION_IDS
        ],
        "rules": rules,
    }
    return specs, basis


# ---------------------------------------------------------------- inputs from the student's data
def plan_inputs(profile: dict[str, Any] | None, stats: dict[str, dict[str, Any]], bank: Bank, attempts: list[dict[str, Any]],
                week_start: date, today: date, now: datetime, kept: list[dict[str, Any]]) -> PlanInputs:
    sections: dict[str, SectionInput] = {}
    for sid in SECTION_IDS:
        answered = [s for s in stats.values() if s.get("section") == sid and has_answered(s)]
        correct = sum(1 for s in answered if s.get("lastCorrect") is True)
        sec = SectionInput(attempted=len(answered), accuracy=round(correct / len(answered), 4) if answered else None)
        topics: dict[str, list[int]] = {}
        for s in answered:
            topic = (bank.questions.get(str(s.get("questionId"))) or {}).get("topic")
            if isinstance(topic, str) and topic.strip():
                bucket = topics.setdefault(topic.strip(), [0, 0])
                bucket[0] += 1
                bucket[1] += 1 if s.get("lastCorrect") is True else 0
        weak = [(c / n, -n, t) for t, (n, c) in topics.items() if n >= TOPIC_MIN_ATTEMPTED and c / n < 0.6]
        if weak:
            acc, neg_n, topic = min(weak)
            sec.weak_topic, sec.weak_topic_accuracy, sec.weak_topic_attempted = topic, round(acc, 4), -neg_n
        sections[sid] = sec
    exam, source = exam_date_for(profile)
    hours = (profile or {}).get("weeklyStudyHours")
    return PlanInputs(
        week_start=week_start,
        today=today,
        exam_date=exam,
        exam_date_source=source,
        weekly_hours=float(hours) if isinstance(hours, (int, float)) and hours > 0 else 10.0,
        study_days=[d for d in (profile or {}).get("studyDays") or [] if isinstance(d, int)],
        level=(profile or {}).get("currentLevel") or "beginner",
        sections=sections,
        mistakes_due=sum(1 for s in stats.values() if is_due(s, now)),
        mocks_submitted=sum(1 for a in attempts if a.get("status") == "submitted"),
        daily_available=bool(bank.questions),
        kept=kept,
    )


# ---------------------------------------------------------------- storage
def _week_tasks(db: SafeFirestore, user_id: str, week_start: date) -> list[tuple[str, dict[str, Any], Any]]:
    query = db.collection(TASKS).where(filter=FieldFilter("userWeek", "==", user_week(user_id, week_start)))
    out = []
    for snap in query.stream(timeout=DB_TIMEOUT):
        data = as_dict(snap) or {}
        if data.get("userId") == user_id:
            out.append((snap.id, data, snap.update_time))
    return out


def _replaceable(task: dict[str, Any], today: date) -> bool:
    """A generated task the generator may overwrite or remove."""
    day = parse_day(task.get("date"))
    return (task.get("source") == "generated" and task.get("status") == "pending" and not task.get("edited")
            and day is not None and day >= today)


def _str(value: Any) -> str | None:
    return value if isinstance(value, str) and value else None


def task_payload(doc_id: str, data: dict[str, Any]) -> dict[str, Any]:
    status = data.get("status") if data.get("status") in ("pending", "done", "skipped") else "pending"
    kind = data.get("type") if data.get("type") in TaskType.__args__ else "custom"  # type: ignore[attr-defined]
    minutes = data.get("minutes")
    count = data.get("questionCount")
    return {
        "id": doc_id,
        "date": _str(data.get("date")) or "",
        "type": kind,
        "title": _str(data.get("title")) or "Study task",
        "detail": _str(data.get("detail")),
        "section": data.get("section") if data.get("section") in SECTION_IDS else None,
        "topic": _str(data.get("topic")),
        "questionCount": count if isinstance(count, int) and not isinstance(count, bool) else None,
        "minutes": minutes if isinstance(minutes, int) and not isinstance(minutes, bool) else 0,
        "href": _str(data.get("href")),
        "status": status,
        "source": "custom" if data.get("source") == "custom" else "generated",
        "generatedBy": _str(data.get("generatedBy")),
        "edited": bool(data.get("edited")),
        "autoCompleted": bool(data.get("autoCompleted")),
        "completedAt": _str(data.get("completedAt")) if status == "done" else None,
        "createdAt": _str(data.get("createdAt")) or "",
        "updatedAt": _str(data.get("updatedAt")) or "",
        "order": data.get("order") if isinstance(data.get("order"), int) else 1000,
    }


def generate_week(db: SafeFirestore, user: CurrentUser, week_start: date) -> None:
    bank = get_bank(db)
    now = utcnow()
    today = local_date(now)
    existing = _week_tasks(db, user.user_id, week_start)
    kept = [{**data, "id": doc_id} for doc_id, data, _ in existing if not _replaceable(data, today)]
    profile = load_profile(db, user.user_id)
    inputs = plan_inputs(profile, user_stats(db, user.user_id), bank, user_attempts(db, bank, user), week_start, today, now, kept)
    specs, _basis = build_week_plan(inputs)
    stamp = iso(now)
    wanted: set[str] = set()
    for spec in specs:
        doc_id = f"{user.user_id}_{week_start.isoformat()}_{spec.pop('key')}"
        wanted.add(doc_id)
        doc = {**spec, "userId": user.user_id, "userWeek": user_week(user.user_id, week_start), "weekStart": week_start.isoformat(),
               "status": "pending", "source": "generated", "generatedBy": RULE_VERSION, "edited": False,
               "autoCompleted": False, "completedAt": None, "updatedAt": stamp}

        def mutate(current: dict[str, Any] | None, doc: dict[str, Any] = doc) -> tuple[dict[str, Any] | None, None]:
            if current is not None and not _replaceable(current, today):
                return None, None  # the student's (done / skipped / edited / moved) task stays as it is
            created = _str((current or {}).get("createdAt")) or stamp
            new = {**doc, "createdAt": created}
            if current is not None and all(current.get(k) == v for k, v in new.items() if k != "updatedAt"):
                return None, None
            return new, None

        occ_update(db, TASKS, doc_id, mutate)
    for doc_id, data, update_time in existing:
        if doc_id in wanted or not _replaceable(data, today):
            continue
        try:
            db.collection(TASKS).document(doc_id).delete(
                option=_FirestoreClient.write_option(last_update_time=update_time), timeout=DB_TIMEOUT)
        except (gexc.FailedPrecondition, gexc.NotFound, gexc.Conflict, gexc.Aborted):
            pass  # changed meanwhile (e.g. marked done) — leave it


# ---------------------------------------------------------------- auto-complete
def auto_complete(db: SafeFirestore, bank: Bank, stats: dict[str, dict[str, Any]], attempts: list[dict[str, Any]],
                  tasks: list[tuple[str, dict[str, Any], Any]], week_start: date, today: date) -> dict[str, dict[str, Any]]:
    """Mark pending tasks done when the matching activity happened. Returns {docId: new fields}."""
    week_end = week_start + timedelta(days=6)
    done: dict[str, dict[str, Any]] = {}
    used_attempts = {t.get("completedByAttempt") for _, t, _ in tasks if t.get("completedByAttempt")}

    def answered_on(day: str) -> list[dict[str, Any]]:
        return [s for s in stats.values() if day in (s.get("answeredDates") or [])]

    # A mock submitted this week completes a planned mock of that kind even if it was planned for a later day;
    # every other task is only checked on or after its own day.
    pending = [(doc_id, t) for doc_id, t, _ in tasks
               if t.get("status") == "pending" and (t.get("type") in MOCK_TYPES or (parse_day(t.get("date")) or date.max) <= today)]
    # Mocks: a submitted attempt of the same kind this week.
    submitted = []
    for att in attempts:
        moment = parse_iso(att.get("submittedAt"))
        if att.get("status") == "submitted" and moment and att.get("id") not in used_attempts:
            day = local_date(moment)
            if week_start <= day <= week_end:
                submitted.append((day, att))
    submitted.sort(key=lambda x: x[0])
    for day, att in submitted:
        kind = "full_mock" if att.get("kind") == "full_mock" else "sectional_mock"
        candidates = [(doc_id, t) for doc_id, t in pending if t.get("type") == kind and doc_id not in done]
        if not candidates:
            continue
        candidates.sort(key=lambda c: (c[1].get("date") != day.isoformat(), str(c[1].get("date"))))
        doc_id = candidates[0][0]
        done[doc_id] = {"completedByAttempt": att.get("id")}
    for doc_id, task in pending:
        if doc_id in done:
            continue
        day = str(task.get("date"))
        kind = task.get("type")
        if kind == "daily_challenge":
            ids = daily_question_ids(bank, day)
            if ids and all(day in ((stats.get(q) or {}).get("answeredDates") or []) for q in ids):
                done[doc_id] = {}
        elif kind == "practice" and task.get("section") in SECTION_IDS:
            need = task.get("questionCount") if isinstance(task.get("questionCount"), int) else 5
            if sum(1 for s in answered_on(day) if s.get("section") == task["section"]) >= need:
                done[doc_id] = {}
        elif kind == "revise_mistakes" and isinstance(task.get("questionCount"), int):
            retried = 0
            for s in answered_on(day):
                first_wrong = parse_iso(s.get("mistakeAt"))
                last = parse_iso(s.get("lastAnsweredAt"))
                if first_wrong and last and local_date(first_wrong).isoformat() < day and local_date(last).isoformat() == day:
                    retried += 1
            if retried >= max(1, task["questionCount"]):
                done[doc_id] = {}
    stamp = iso(utcnow())
    applied: dict[str, dict[str, Any]] = {}
    for doc_id, extra in done.items():
        fields = {"status": "done", "autoCompleted": True, "completedAt": stamp, "updatedAt": stamp, **extra}

        def mutate(current: dict[str, Any] | None, fields: dict[str, Any] = fields) -> tuple[dict[str, Any] | None, bool]:
            if current is None or current.get("status") != "pending":
                return None, False
            return fields, True

        if occ_update(db, TASKS, doc_id, mutate):
            applied[doc_id] = fields
    return applied


